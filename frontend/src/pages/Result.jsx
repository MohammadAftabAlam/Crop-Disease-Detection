import React from "react";
import { Link, useLocation } from "react-router-dom";
import PredictionCard from "../components/PredictionCard";

function Result() {
  const location = useLocation();

  const result = location.state?.result;

  if (!result) {
    return (
      <div className="result-page">
        <div className="result-empty">
          <h2>No Prediction Result Found</h2>

          <p>
            Please upload a crop image and perform detection first.
          </p>

          <Link to="/detect" className="primary-button">
            🔍 Detect Disease
          </Link>
        </div>
      </div>
    );
  }

  const prediction = result.prediction || result;

  const crop = prediction.crop || "Unknown Crop";
  const disease = prediction.disease || "Unknown Disease";
  const confidence = Number(prediction.confidence || 0);

  const remedy =
    prediction.remedy || "No remedy information available.";

  return (
    <div className="result-page">

      <div className="result-header">
        <h1>🔬 Detection Result</h1>

        <p>
          Here is the result generated by the AI model.
        </p>
      </div>

      <PredictionCard
        crop={crop}
        disease={disease}
        confidence={confidence}
        remedy={remedy}
      />

      <div className="result-actions">

        <Link to="/detect" className="primary-button">
          🔄 Analyze Another Image
        </Link>

        <Link to="/history" className="secondary-button">
          📋 View History
        </Link>

      </div>

    </div>
  );
}

export default Result;